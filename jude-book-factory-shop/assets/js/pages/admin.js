/*
 * Catalogue manager — edits a local draft of products.js and downloads it.
 * Runs entirely in the browser; nothing is uploaded.
 */
(function (JBF) {
  "use strict";
  var ui = JBF.ui;
  var DRAFT_KEY = "jbf_catalogue_draft_v1";
  var products = [];
  var categories = (JBF.categories || []).slice();
  var editing = null; // index or -1 for new

  function clone(x) { return JSON.parse(JSON.stringify(x)); }
  function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "").slice(0, 60); }

  function load() {
    try {
      var d = JBF.storage.get(DRAFT_KEY);
      if (d) { products = JSON.parse(d); status("Loaded your unsaved draft (" + products.length + " products). Download products.js to publish it."); return; }
    } catch (e) { /* ignore */ }
    products = clone(JBF.products || []);
  }
  function save() { JBF.storage.set(DRAFT_KEY, JSON.stringify(products)); }

  function status(msg) {
    var s = document.getElementById("status");
    s.textContent = msg;
    s.hidden = !msg;
  }

  function catName(id) {
    var c = categories.find(function (x) { return x.id === id; });
    return c ? c.name : id + " (unknown)";
  }

  function renderRows() {
    var tb = document.getElementById("rows");
    if (!products.length) {
      tb.innerHTML = '<tr><td colspan="7">No products yet. Press "Add product" or import a CSV.</td></tr>';
      return;
    }
    tb.innerHTML = products.map(function (p, i) {
      return "<tr>" +
        "<td><strong>" + ui.esc(p.title) + "</strong><br><span class=\"small\">" + ui.esc(p.brand || "") + (p.faireRef ? " · " + ui.esc(p.faireRef) : "") + "</span></td>" +
        "<td>" + ui.esc(catName(p.category)) + "</td>" +
        "<td>" + JBF.money(p.price || 0) + "</td>" +
        "<td>" + (p.rrp ? JBF.money(p.rrp) : "—") + "</td>" +
        "<td>" + (p.stock || 0) + "</td>" +
        "<td>" + (p.featured ? "★" : "") + "</td>" +
        '<td style="white-space:nowrap"><button class="link-btn" style="color:var(--blue-ink)" type="button" data-edit="' + i + '">Edit</button> ' +
        '<button class="link-btn" type="button" data-del="' + i + '">Delete</button></td></tr>';
    }).join("");
  }

  function fillCategories() {
    document.getElementById("f-category").innerHTML = categories.map(function (c) {
      return '<option value="' + ui.esc(c.id) + '">' + ui.esc(c.name) + "</option>";
    }).join("");
  }

  function openEditor(i) {
    editing = i;
    var p = i >= 0 ? products[i] : { id: "", title: "", brand: "", category: categories[0] && categories[0].id, price: "", rrp: "", stock: 1, image: "", description: "", tags: [], featured: false, faireRef: "", ageRange: "" };
    var f = document.getElementById("editor");
    document.getElementById("editor-title").textContent = i >= 0 ? "Edit product" : "Add product";
    f.elements.title.value = p.title || "";
    f.elements.brand.value = p.brand || "";
    f.elements.category.value = p.category || "";
    f.elements.id.value = p.id || "";
    f.elements.price.value = p.price === "" ? "" : p.price;
    f.elements.rrp.value = p.rrp || "";
    f.elements.stock.value = p.stock == null ? 0 : p.stock;
    f.elements.ageRange.value = p.ageRange || "";
    f.elements.image.value = p.image || "";
    f.elements.faireRef.value = p.faireRef || "";
    f.elements.description.value = p.description || "";
    f.elements.tags.value = (p.tags || []).join(", ");
    f.elements.featured.checked = !!p.featured;
    f.hidden = false;
    f.scrollIntoView({ behavior: "smooth", block: "start" });
    f.elements.title.focus({ preventScroll: true });
  }

  function uniqueId(base, skipIndex) {
    var id = base || "product", n = 2;
    while (products.some(function (p, i) { return i !== skipIndex && p.id === id; })) id = base + "-" + n++;
    return id;
  }

  function fromForm(f) {
    var e = f.elements;
    var p = {
      id: uniqueId(slug(e.id.value) || slug(e.title.value), editing),
      title: e.title.value.trim(),
      brand: e.brand.value.trim(),
      category: e.category.value,
      price: Math.round(parseFloat(e.price.value || 0) * 100) / 100,
      rrp: e.rrp.value ? Math.round(parseFloat(e.rrp.value) * 100) / 100 : null,
      stock: parseInt(e.stock.value || 0, 10),
      image: e.image.value.trim(),
      description: e.description.value.trim(),
      tags: e.tags.value.split(",").map(function (t) { return t.trim(); }).filter(Boolean),
      featured: e.featured.checked,
      faireRef: e.faireRef.value.trim()
    };
    if (e.ageRange.value.trim()) p.ageRange = e.ageRange.value.trim();
    if (!p.rrp) delete p.rrp;
    return p;
  }

  // ---------- Export ----------
  function buildFile() {
    return "/*\n * Product catalogue — generated by admin/catalogue.html on " + new Date().toLocaleString("en-GB") + "\n" +
      " * You can keep editing this file by hand, or re-open the catalogue manager.\n */\n" +
      "window.JBF = window.JBF || {};\n\n" +
      "JBF.categories = " + JSON.stringify(categories, null, 2) + ";\n\n" +
      "JBF.products = " + JSON.stringify(products, null, 2) + ";\n";
  }
  function download(name, text, type) {
    var blob = new Blob([text], { type: type });
    var a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = name;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () { URL.revokeObjectURL(a.href); a.remove(); }, 500);
  }

  // ---------- CSV ----------
  function parseCSV(text) {
    var rows = [], row = [], field = "", q = false;
    text = text.replace(/^﻿/, "");
    for (var i = 0; i < text.length; i++) {
      var c = text[i];
      if (q) {
        if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; }
        else field += c;
      } else if (c === '"') q = true;
      else if (c === ",") { row.push(field); field = ""; }
      else if (c === "\n" || c === "\r") {
        if (c === "\r" && text[i + 1] === "\n") i++;
        row.push(field); field = "";
        if (row.some(function (x) { return x.trim() !== ""; })) rows.push(row);
        row = [];
      } else field += c;
    }
    row.push(field);
    if (row.some(function (x) { return x.trim() !== ""; })) rows.push(row);
    return rows;
  }

  var HEADER_MAP = {
    id: ["id", "handle"],
    title: ["title", "name", "product", "productname"],
    brand: ["brand", "vendor", "maker", "brandname"],
    category: ["category", "type", "producttype"],
    price: ["price", "ourprice", "sellingprice", "saleprice"],
    rrp: ["rrp", "retailprice", "msrp", "compareatprice", "wasprice"],
    stock: ["stock", "quantity", "qty", "inventory"],
    image: ["image", "imageurl", "photo", "picture"],
    description: ["description", "details"],
    tags: ["tags", "keywords", "searchwords"],
    featured: ["featured"],
    faireRef: ["faireref", "sku", "fairesku", "reference", "ordernumber"],
    ageRange: ["agerange", "age", "ages"]
  };

  function matchCategory(v) {
    var s = slug(v);
    var c = categories.find(function (x) { return x.id === s || slug(x.name) === s || slug(x.name).indexOf(s) === 0; });
    return c ? c.id : null;
  }

  function importCSV(text) {
    var rows = parseCSV(text);
    if (rows.length < 2) { status("That CSV has no product rows."); return; }
    var head = rows[0].map(function (h) { return h.toLowerCase().replace(/[^a-z0-9]/g, ""); });
    var col = {};
    Object.keys(HEADER_MAP).forEach(function (k) {
      var idx = head.findIndex(function (h) { return HEADER_MAP[k].indexOf(h) !== -1; });
      if (idx !== -1) col[k] = idx;
    });
    if (col.title == null || col.price == null) { status("The CSV needs at least a 'title' and a 'price' column. Download the template to see the format."); return; }
    var added = 0, updated = 0, unknownCats = 0;
    rows.slice(1).forEach(function (r) {
      function get(k) { return col[k] == null ? "" : String(r[col[k]] || "").trim(); }
      if (!get("title")) return;
      var cat = matchCategory(get("category"));
      if (!cat) { unknownCats++; cat = categories[0] && categories[0].id; }
      var num = function (v) { var n = parseFloat(String(v).replace(/[£$,]/g, "")); return isNaN(n) ? null : Math.round(n * 100) / 100; };
      var p = {
        id: slug(get("id")) || slug(get("title")),
        title: get("title"),
        brand: get("brand"),
        category: cat,
        price: num(get("price")) || 0,
        rrp: num(get("rrp")),
        stock: parseInt(get("stock") || "1", 10) || 0,
        image: get("image"),
        description: get("description"),
        tags: get("tags").split(/[;,]/).map(function (t) { return t.trim(); }).filter(Boolean),
        featured: /^(y|yes|true|1)$/i.test(get("featured")),
        faireRef: get("faireRef")
      };
      if (get("ageRange")) p.ageRange = get("ageRange");
      if (!p.rrp) delete p.rrp;
      var i = products.findIndex(function (x) { return x.id === p.id; });
      if (i >= 0) { products[i] = Object.assign(products[i], p); updated++; }
      else { products.push(p); added++; }
    });
    save(); renderRows();
    status("Imported: " + added + " added, " + updated + " updated." +
      (unknownCats ? " " + unknownCats + " had an unrecognised category and were put in '" + catName(categories[0].id) + "' — please check them." : "") +
      " Remember to download products.js.");
  }

  var TEMPLATE = "title,brand,category,price,rrp,stock,image,description,tags,featured,sku,age range\n" +
    "\"Wooden Rainbow Stacker\",\"Maker Name\",Toys & Play,16.50,24.00,4,assets/img/products/rainbow.jpg,\"Hand-finished wooden rainbow.\",\"wooden; eco\",yes,FAIRE-12345,18m+\n";

  // ---------- Wire up ----------
  document.addEventListener("DOMContentLoaded", function () {
    load();
    fillCategories();
    renderRows();

    document.getElementById("add").addEventListener("click", function () { openEditor(-1); });
    document.getElementById("cancel").addEventListener("click", function () { document.getElementById("editor").hidden = true; });
    document.getElementById("rows").addEventListener("click", function (e) {
      var b = e.target.closest("button");
      if (!b) return;
      if (b.hasAttribute("data-edit")) openEditor(parseInt(b.getAttribute("data-edit"), 10));
      if (b.hasAttribute("data-del")) {
        var i = parseInt(b.getAttribute("data-del"), 10);
        if (window.confirm("Delete \"" + products[i].title + "\"?")) { products.splice(i, 1); save(); renderRows(); }
      }
    });
    document.getElementById("editor").addEventListener("submit", function (e) {
      e.preventDefault();
      var f = e.target;
      if (!f.checkValidity()) { f.reportValidity(); return; }
      var p = fromForm(f);
      if (editing >= 0) products[editing] = p; else products.push(p);
      save(); renderRows();
      f.hidden = true;
      status("Saved \"" + p.title + "\". Download products.js when you're finished.");
    });
    document.getElementById("f-image-pick").addEventListener("change", function (e) {
      var file = e.target.files && e.target.files[0];
      if (file) {
        document.getElementById("f-image").value = "assets/img/products/" + file.name;
        status("Remember to copy " + file.name + " into the assets/img/products/ folder.");
      }
    });
    document.getElementById("download").addEventListener("click", function () {
      download("products.js", buildFile(), "text/javascript");
      status("Downloaded. Replace assets/js/products.js with this file, and set demoMode to false in config.js when you go live.");
    });
    document.getElementById("template").addEventListener("click", function () {
      download("products-template.csv", TEMPLATE, "text/csv");
    });
    document.getElementById("csv").addEventListener("change", function (e) {
      var file = e.target.files && e.target.files[0];
      if (!file) return;
      var r = new FileReader();
      r.onload = function () { importCSV(String(r.result)); e.target.value = ""; };
      r.readAsText(file);
    });
    document.getElementById("remove-samples").addEventListener("click", function () {
      var n = products.filter(function (p) { return /^sample-/.test(p.id); }).length;
      if (!n) { status("There are no sample products left."); return; }
      if (window.confirm("Remove all " + n + " sample products?")) {
        products = products.filter(function (p) { return !/^sample-/.test(p.id); });
        save(); renderRows();
        status("Removed " + n + " sample products.");
      }
    });
    document.getElementById("reset").addEventListener("click", function () {
      if (window.confirm("Discard your draft and reload products.js?")) {
        JBF.storage.remove(DRAFT_KEY);
        products = clone(JBF.products || []);
        renderRows();
        status("Draft discarded.");
      }
    });
  });
})(window.JBF);
